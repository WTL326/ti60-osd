/******************************************************************************
*
* @file crc16.c: 0xBB 协议使用的 CRC-16/CCITT 校验
*
* @note 参数集与用法说明见 crc16.h。
*
******************************************************************************/
#include "crc16.h"

/* 生成多项式。CRC-16/CCITT 用的是 0x1021，即二进制 1_0000_0010_0001，
 * 对应 x^16 + x^12 + x^5 + 1。之所以写成十六进制常量而不是"1 << 12 | ..."，
 * 是为了和 RTL 里的 16'h1021 一眼能对上。
 *
 * 关于 U 后缀：0x1021U 中的 U 表示这是无符号常量。C 语言里如果常量带符号，
 * 参与位运算时可能被按有符号数处理，产生意料之外的符号扩展。本文件全是
 * 无符号运算，加 U 是防御性写法（也是这类嵌入式代码的常见风格）。*/
#define CRC16_CCITT_POLY 0x1021U

uint16_t crc16_ccitt_update(uint16_t crc, uint8_t data)
{
    /* 第一步：把新字节异或到累计值的高 8 位。
     *
     * 拆开看这行：data 是 8 位的，先强制转成 uint16_t 再左移 8 位，让它落在
     * 高字节；然后与 crc 异或。为什么必须先转型？C 语言里 uint8_t 参与运算时
     * 会先"整型提升"成 int，左移 8 位后还是 int，直接和 uint16_t 异或虽然结果
     * 正确，但中间类型带符号、语义不清晰。显式转型让每一步的类型都一目了然。
     *
     * 最外层的 (uint16_t) 是为了把结果截断回 16 位。RTL 里 c 就是 16 位寄存器，
     * 溢出自然丢弃高位；C 里必须显式截断才能和 RTL 完全一致。*/
    uint16_t c = (uint16_t)(crc ^ (uint16_t)((uint16_t)data << 8));
    int      n;

    /* 第二步：循环 8 次，每次处理一位。
     *
     * 这是"逐位法"CRC，每一步做的是：
     *   - 看当前最高位（bit15）是不是 1；
     *   - 是 1 就左移一位、再异或生成多项式（相当于做减法）；
     *   - 是 0 就只左移一位。
     *
     * 这段逻辑与 RTL 的
     *     c = c[15] ? ((c << 1) ^ 16'h1021) : (c << 1);
     * 完全对应，连"先判最高位再移位"的顺序都一样。
     *
     * 为什么不用查表法（预生成 256 项的表，一次处理一个字节）：
     * 查表要占 512 字节常量空间，而本模块的调用频率是"每个 body 字节一次"，
     * 在 115200 波特率下每秒最多一万多次，逐位法（每字节 8 次循环）绰绰有余。
     * 用一点 CPU 换掉 512 字节 Flash，对软核更划算。*/
    for (n = 0; n < 8; n++) {
        if ((c & 0x8000U) != 0U) {
            /* 0x8000 就是只保留 bit15 的掩码。用 & 判断而不是写成 (c >> 15)，
             * 是为了和 RTL 的 c[15] 取值写法更贴近。*/
            c = (uint16_t)((uint16_t)(c << 1) ^ CRC16_CCITT_POLY);
        } else {
            c = (uint16_t)(c << 1);
        }
    }
    return c;
}
