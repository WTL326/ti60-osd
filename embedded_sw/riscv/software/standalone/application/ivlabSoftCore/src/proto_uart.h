/******************************************************************************
*
* @file proto_uart.h: uart1 协议端点的硬件层
*
* @brief 提供在 uart1 上收发 0xBB 协议字节的底层原语：初始化、中断接收、
*        带超时的发送。
*
* @note 本层**刻意与调试输出通道完全无关**。这里每一个字节都直接读写 uart1 的
*       寄存器（PROTO_UART_BASE），绝不碰 BSP 的打印栈。
*
*       为什么这条界限必须守死？因为调试输出走的是 semihosting，而 semihosting
*       每写一个字符都要发一条 ebreak 让主机来取、期间 CPU 完全停住（详见
*       design 决策 5）。如果协议应答也走那条路，那么"改一个调试开关"就会
*       改变协议的行为，而且调速调试输出的多少会直接影响协议能否及时应答。
*       把两者在寄存器层面彻底分开之后，无论调试通道怎么设置、停顿多久，
*       协议的行为都是确定的。
*
* @note 当 SoC 没有暴露 uart1（soc.h 里没有 SYSTEM_UART_1_IO_CTRL）时，本模块
*       整体编译成"什么都不做"的空实现。这样应用仍然能构建、调试输出照常可用，
*       只是协议功能不可用。为什么要这样兜底：uart1 需要重新生成 SoC 才会出现，
*       如果硬依赖它，在 SoC 还没生成好的阶段整个工程一行都编译不过，连调试
*       输出都没法验证。
*
******************************************************************************/
#ifndef IVLAB_PROTO_UART_H
#define IVLAB_PROTO_UART_H

#include <stdint.h>

/* uart1 接收环形缓冲的容量（字节）。必须是 2 的幂——原因见 proto_uart.c 里
 * 取模运算的注释。
 *
 * 为什么取 512：uart1 跑 115200 8N1，每个字节约 87 微秒，512 字节约 44 毫秒。
 * 这个缓冲要能吸收"主循环暂时没空取字节"的那段时间——最主要的就是调试输出
 * 造成的停滞。缓冲越大越安全，但代价是 RAM；44 毫秒对目前的使用场景足够。*/
#define PROTO_RX_RING_SIZE 512U

/* proto_uart_write() 每个字节最多自旋等待多少次。
 * 50 MHz 下约 12 毫秒，远大于健康状态下 UART 发送 FIFO 腾出一个位置所需的时间，
 * 但又不至于让一个坏掉的 UART 把主循环卡死。
 *
 * 为什么要有这个上限：UART 的发送函数在 FIFO 满时会一直等（bsp 里的写法是
 * `while(...)` 死等）。如果 UART 因为时钟、引脚或寄存器配置问题永远不排空，
 * 死等就意味着软核彻底停摆、连协议接收都停了。给一个上限，最坏情况是丢掉
 * 一个应答，但软核还能继续工作。*/
#define PROTO_TX_TIMEOUT_SPINS 100000U

/* SoC 是否提供了 uart1。这两个宏把"平台能力"集中在一处，其它模块只需判断
 * PROTO_ENDPOINT_AVAILABLE，不必各自去 include soc.h 再检查。
 *
 * 用 #if defined(...) 而不是 #ifdef：效果相同，但 #if defined 能直接配合
 * && / || 组合多个条件，风格上更统一。*/
#if defined(SYSTEM_UART_1_IO_CTRL)
#define PROTO_UART_BASE            SYSTEM_UART_1_IO_CTRL
#define PROTO_ENDPOINT_AVAILABLE   1
#else
#define PROTO_ENDPOINT_AVAILABLE   0
#endif

/******************************************************************************
* @brief 初始化 uart1：配置成 115200 8N1，并使能接收中断。
*
* @note 分频系数与波特率参数的算法必须和 bsp_init() 对 uart0 的做法一致，
*       否则两条串口跑在不同波特率上，上位机会有一路收不到。
*
* @note uart1 不可用时为空函数。
******************************************************************************/
void proto_uart_init(void);

/******************************************************************************
* @brief 从接收环里取出一个字节。
*
* @param byte 输出：取到的字节。
* @return 1 表示取到了；0 表示环是空的。
*
* @note 只能由主循环调用。中断服务程序是本环唯一的"写入者"，主循环是唯一的
*       "读取者"——这种"单写单读"是最简单的并发模型，不需要关中断就能保证
*       数据一致（理由见 proto_uart.c 中读写指针的说明）。
******************************************************************************/
int proto_uart_rx_pop(uint8_t *byte);

/******************************************************************************
* @brief 当前接收环里还积压着多少字节。
*
* @note 主循环用它判断"是否还有要处理的字节"。返回 0 表示可以去做别的事了。
******************************************************************************/
uint32_t proto_uart_rx_pending(void);

/******************************************************************************
* @brief 因为接收环满而被丢掉的字节数。
*
* @note 这个数非零说明主循环有过较长时间的停顿（比如调试输出卡住太久），
*       接收环被灌满了。
*
* @note **但它不是"丢字节"的全部**——它只覆盖"中断服务程序跑了、但环已满"
*       这一种情况。还有一种它完全看不见：CPU 被 semihosting 停住时中断根本
*       不被响应，uart1 的硬件 FIFO（128 字节，115200 下约 11 ms 的量）会自己
*       溢出并静默丢字节。那一种由 proto_uart_fifo_overflow() 报告。
*       两个数是两种不同的病因，必须分开看。
******************************************************************************/
uint32_t proto_uart_rx_dropped(void);

/******************************************************************************
* @brief uart1 硬件接收 FIFO 累计溢出次数（粘滞计数）。
*
* @return 自启动以来观察到的溢出次数，0 表示从未溢出。
*
* @note 为什么需要它：CPU 被 semihosting 停住（`ebreak` → 调试模块停住 hart）
*       期间**任何中断都不被响应**，uart1 的接收 FIFO 在这段时间里无人搬运，
*       超过 128 字节就自己丢数据。这种丢失发生在硬件里，接收环的计数
*       （proto_uart_rx_dropped）看不到，是本应用最难从现象反推的一类故障。
*       把它报出来，"帧莫名其妙少了"就不再需要靠猜。
*
* @note 硬件标志置位后一直保持，直到写 1 清除，所以本函数采用"读取即检查、
*       发现就累计并清零"的**粘滞**做法：调用时机不影响统计结果，瞬时事件也
*       不会在两次调用之间丢掉。
******************************************************************************/
uint32_t proto_uart_fifo_overflow(void);

/******************************************************************************
* @brief 把 uart1 接收 FIFO 里的字节搬进接收环，然后重新使能中断。
*
* @note 这是本模块里唯一允许在中断上下文运行的函数。它**只搬字节**：不解析、
*       不判断、不输出任何信息。
*       为什么这么严格：中断里做的事情越少，关中断的时间越短，主循环和其它
*       中断受到的打扰就越小。尤其不能在中断里做任何输出——那会让 CPU 在
*       中断里停住等主机，整个系统都会卡死。
*
* @note 由 trap() 在处理外部中断时调用（见 main.c）。
******************************************************************************/
void proto_uart_isr(void);

/******************************************************************************
* @brief 在 uart1 上发送一段字节，等待空间时有上限。
*
* @param data 要发送的数据，允许为空（此时直接返回失败）。
* @param len  字节数。
* @return 1 表示每个字节都交给了 UART；0 表示等超时了。
*
* @note 返回值刻意保留：调用者目前不处理失败，但"发送可能失败"这件事在接口上
*       写清楚，比假装它一定成功要好——将来若要统计发送失败率，不用改接口。
*
* @note 这个函数是**阻塞**的：它要等发送 FIFO 有空间。这是有意的设计——
*       一个 ACK 只有 10 字节，115200 下约 868 微秒，阻塞时间可以接受；而
*       换来的是"发送期间不解析新字节"，从而保证每个完整帧都能拿到自己的
*       ACK（详见 design 决策 4）。
******************************************************************************/
int proto_uart_write(const uint8_t *data, uint32_t len);

#endif /* IVLAB_PROTO_UART_H */
