/* =============================================================================
 * OSD 引擎 —— 把"协议判断 → 渲染 → 提交 → 应答"这条链固定成一处
 *
 * 为什么不直接写在 main.c 的循环里：
 *   main.c 依赖 bsp.h（UART/PLIC/semihosting），而 qemu 上的离机测试只能链接
 *   不碰硬件的模块。把这条链抽出来之后，"提交完成后才回应答"（协议 §5.5）
 *   这条最容易写错的顺序规则就有了自动化验证，不必靠上板看现象。
 *   main.c 的循环因此退化成"取字节 → 解析 → 交给引擎 → 把引擎给出的应答写出去"。
 *
 * 一次命令 = 一次渲染 = 一次提交（沿用上游共识）；没有命令就不产生任何写入。
 * =============================================================================
 */
#ifndef OSD_ENGINE_H
#define OSD_ENGINE_H

#include <stdint.h>
#include "frame.h"
#include "protocol.h"

/******************************************************************************
* @brief 上电初始化：清状态、把两块位图整体清零、渲染并提交第一屏。
*
* @note 两块**都要**清零，不能只清将要写的那一块：位图是透明底（位 = 0 即视频
*       透传），而乒乓意味着两块会轮流上前台。只清一块的话，另一块上前台时
*       框外会露出上一版内容。上游用一个字节的"清屏"就覆盖了这条，
*       这里保持同样的做法。
******************************************************************************/
void osd_engine_boot(void);

/******************************************************************************
* @brief 处理一个已经收完整的帧：判断 →（必要时）渲染并提交 → 产出待发应答。
*
* @param stats 收包统计，会被更新。
* @param frame 解析好的帧。
* @param resp  输出：处理决定，供调用方打日志（reason / command_name / status）。
* @param ack   输出：待发送的应答字节，至少 PROTOCOL_ACK_MAX 字节。
* @return 待发送的字节数；0 表示这一帧不应答。
*
* @note **顺序是这里唯一重要的事**：SET_VIEW / SET_IMAGE_VALUES 的**成功**应答
*       必须等 `composer_render()` 与 `canvas_commit()` 都做完再发出去
*       （协议 §5.5：TI60 在完成非活动 bank 写入并提交后才返回成功）。
*       上位机收到成功就开始轮询/发下一条，此时画布还没写完的话，它读到的
*       是半屏菜单。失败应答不渲染、立即回 —— 没有画布要等。
*
* @note 渲染只在"确实接受了命令"时发生。查询（QUERY_VIEW）与失败帧都不渲染，
*       所以它们不产生任何 AXI 写入 —— 这是"无命令则零写入"的落点。
******************************************************************************/
uint8_t osd_engine_handle(protocol_stats_t *stats, const frame_t *frame,
                          protocol_response_t *resp, uint8_t *ack);

/* --- 供日志与测试观察的旁路信息 --- */

int osd_engine_render_count(void);   /* 累计渲染+提交次数 */
int osd_engine_back_block(void);     /* 当前后台块（0 = A / 1 = B） */
int osd_engine_last_deferred(void);  /* 上一次应答是否走了"延迟到提交后"这支 */

#endif /* OSD_ENGINE_H */
