/******************************************************************************
* @brief 清空日志环并清零计数。
******************************************************************************/
void app_log_init(void)
{
    s_head = 0U;
    s_tail = 0U;
    s_dropped = 0U;
    s_once_mask = 0U;      /* 清掉"已报过"的位，让 app_log_once 重新从首次开始 */
}

/******************************************************************************
* @brief 队列里还有多少字符。
*
* @note 与 proto_uart.c 里同样的环形缓冲技巧：无符号减法 + 掩码取模。
******************************************************************************/
uint32_t app_log_pending(void)
{
    return (s_head - s_tail) & (APP_LOG_RING_SIZE - 1U);
}

/******************************************************************************
* @brief 被整条丢弃的消息数。
******************************************************************************/
uint32_t app_log_dropped(void)
{
    return s_dropped;
}

/******************************************************************************
* @brief 格式化并排队的实际实现（供 app_log / app_log_once 共用）。
*
* @param format 格式串。
* @param ap     已经由调用者 va_start 好的可变参数列表。
*
* @note 流程是"先在栈上格式化，再整条搬进环"。
*       为什么要两段式：格式化需要一块连续的缓冲来倒着写数字（见 emit_uint），
*       而环形缓冲是首尾相接的、不连续，没法直接往里格式化。所以先写到栈上的
*       msg[]，格式化完了再整条复制进环。
*       代价是这 160 字节的栈空间——软核的栈有 4 KB，够用。
*
* @note 判断"放不下"用的是 `(used + 1U) > space`，那个 +1 是给消息末尾追加的
*       换行符留位置。**先判断再写入**，所以不会出现"写了一半发现放不下"的
*       情况——这正是"整条进队或整条丢弃"的实现方式。
*
* @note 为什么单独抽成 static 函数：`app_log` 与 `app_log_once` 只差"要不要
*       先过一道闸"，入队逻辑完全一样。抽出来之后，两者共用同一份实现，
*       将来改入队规则（比如环大小、丢弃策略）只需改一处。
******************************************************************************/
static void app_log_v(const char *format, va_list ap)
{
    char     msg[APP_LOG_MSG_MAX];
    uint32_t used;
    uint32_t i;
    uint32_t space;

    if (format == 0) {
        return;
    }

    used = app_vformat(msg, sizeof(msg), format, ap);

    /* 格式化结果为空就不必进队了。*/
    if (used == 0U) {
        return;
    }

    /* 环里还剩多少可用空间。减 1 是为了留一个字节区分"空"和"满"——
     * 环形缓冲的经典做法：始终空一格，靠 head == tail 判断空。*/
    space = (APP_LOG_RING_SIZE - 1U) - app_log_pending();
    if ((used + 1U) > space) {
        s_dropped++;           /* 放不下整条，丢掉并计数 */
        return;
    }

    /* 逐字节搬进环：放消息正文……*/
    for (i = 0U; i < used; i++) {
        s_ring[s_head] = msg[i];
        s_head = (s_head + 1U) & (APP_LOG_RING_SIZE - 1U);
    }
    /* ……再补一个换行，让每条日志各占一行。自动补换行是为了让调用点
     * 不必自己写 "\n"，也避免有的地方写了有的地方忘了、日志连成一片。
     *
     * 这里补的是**逻辑换行**（只有 '\n' 一个字节）。真正上串口需要的
     * "\r\n" 两个字节由 app_log_flush() 在发送前展开，理由见那个函数的说明。*/
    s_ring[s_head] = '\n';
    s_head = (s_head + 1U) & (APP_LOG_RING_SIZE - 1U);
}

/******************************************************************************
* @brief 格式化一条消息并排进队列。
*
* @param format 格式串，后面跟可变参数。
******************************************************************************/
void app_log(const char *format, ...)
{
    va_list ap;

    va_start(ap, format);
    app_log_v(format, ap);
    va_end(ap);
}

/******************************************************************************
* @brief 同一"类"消息只报首次；之后再调用不再产生任何输出。
*
* @param bitno  类别编号，0–31。习惯上直接传枚举值（如失败原因码）。
* @param format 格式串，后面跟可变参数。
*
* @note 为什么需要它——这是实测踩出来的：本应用在"只做协议框架"阶段，每个掩膜
*       帧都会失败（子项未实现），于是**每帧打一行日志**。而日志每发一段都要经
*       semihosting 让 CPU 停下等主机，uart1 的接收中断在此期间不被服务；接收环
*       只有 512 字节（约 44 ms 的量），而一个 4103 字节的分块要 356 ms 才收完。
*       上位机一收到应答就发下一个包，于是"分块正在到达时软核正卡在日志停顿里"
*       必然发生 → 接收环溢出 → 丢字节 → 解析器失步、后续帧被吞。
*       实测：26 个包只回了 10 个应答。
*       把重复的失败压成"每类一行"之后，整轮上传的日志量从 26 行降到几行，
*       停顿次数随之降到可忽略，协议不再被调试输出拖垮。
*
* @note 语义是"这一类**首次**出现时报告"。所以它不会掩盖新问题：任何一类新的
*       失败方式都一定会被报出来。量则由周期性的 stats 汇总行体现。
*
* @note bitno MUST 小于 32。C 语言里 `1U << 32` 是**未定义行为**（不是简单
*       地得到 0），可能把其它位搅乱。这里显式挡住，因为 bitno 常直接来自枚举，
*       将来给枚举加值时就可能越界，而那种 bug 极难查。
******************************************************************************/
void app_log_once(uint32_t bitno, const char *format, ...)
{
    va_list ap;

    if (bitno >= 32U) {
        return;                    /* 越界：宁可不输出，也不能移位越界 */
    }
    if ((s_once_mask & (1U << bitno)) != 0U) {
        return;                    /* 这一类已经报过了 */
    }
    s_once_mask |= (1U << bitno);

    va_start(ap, format);
    app_log_v(format, ap);
    va_end(ap);
}

/******************************************************************************
* @brief 把队列里最多 APP_LOG_CHUNK 个字符发出去（并把换行展开成回车+换行）。
*
* @return 实际发出的字符数（展开之后的字节数）。
*
* @note 这是本模块唯一碰硬件的函数。它把一段字符从环里搬到连续的暂存区
*       s_emit[]，再一次性交给打印函数。
*
*       为什么要先搬：环是首尾相接的，一段日志可能正好跨过环的末端（前一半在
*       尾部、后一半在头部）。打印函数需要的是一个连续的、以 '\0' 结尾的字符串，
*       所以必须先拼成连续的一段。
*
* @note 为什么在这里把 '\n' 展开成 "\r\n"——这是本函数最容易看漏的一点。
*       终端里这两个字符分工不同：
*           '\r'（CR，0x0D）把光标送回**行首**
*           '\n'（LF，0x0A）把光标**下移一行**，但**停在原来的列**
*       只发 '\n' 的话，光标下移却不回行首，第二条日志就接着上一条的末尾往后排，
*       几条之后输出会呈现**阶梯状**，完全没法看。
*       所以真正上串口（或调试控制台）的字节里，换行必须是 "\r\n" 两个字符。
*       本工程的既有代码也是这个惯例：memTest、uartInterruptDemo 里每一条打印
*       都显式写 "\r\n"。BSP 的打印库不做任何换行转换，字节是原样透传的。
*
*       为什么放在这里展开，而不是在 app_log() 入队时就写好 "\r\n"：
*       环里保存的是"逻辑文本"（换行就是 '\n' 一个字节），只有真正要发给硬件的
*       那一刻才转成"线路格式"。好处是转换只存在于这一处——无论 '\n' 是
*       app_log() 自动补的，还是调用者在消息正文里自己写的，都会正确换行。
*
* @note 末尾多留一个字节给 '\0'（s_emit 定义为 CHUNK+1 大小），
*       s_emit[out] = '\0' 就是补结束符——这一句不能省，否则打印函数会越过
*       有效内容继续往后读。
******************************************************************************/
uint32_t app_log_flush(void)
{
    /* pending 在循环开始前取一次就够了：本函数是环的唯一消费者，
     * 循环里 s_tail 只会往前走，所以 pending 就是"这次最多能取多少"。*/
    uint32_t pending = app_log_pending();
    uint32_t consumed = 0U;     /* 已从环里取走的源字节数 */
    uint32_t out = 0U;          /* 已写入 s_emit 的输出字节数 */
    char     c;

    if (pending == 0U) {
        return 0U;              /* 没东西可发，不碰硬件 */
    }

    /* 退出条件有两个：
     *   consumed < pending —— 还有源字节没取
     *   out < APP_LOG_CHUNK —— 输出还没到本次上限（保证单次停顿可控）
     * 两个都要满足才继续。*/
    while ((consumed < pending) && (out < APP_LOG_CHUNK)) {
        /* 先"看一眼"当前字节，并不立刻消费它——因为遇到 '\n' 时可能需要
         * 两个输出位置，万一只剩一个位置就得停在这里下次再发。*/
        c = s_ring[s_tail];

        if (c == '\n') {
            /* '\n' 要展开成两个字节。若剩余空间只够放一个，就跳出循环、
             * 把这个 '\n' **留在环里**（s_tail 不动）等下次再发。
             *
             * 为什么不干脆只发半个：只发 '\r' 会让光标回到行首却不换行，
             * 后半条日志会覆盖在当前行上；只发 '\n' 又会阶梯错位。
             * 要么整对发出，要么一个都不发。
             *
             * 注：APP_LOG_CHUNK 为 32，所以 out==0 时这个条件必然不成立，
             * 不会出现"一个字节都取不出来"的死循环。*/
            if ((out + 2U) > APP_LOG_CHUNK) {
                break;
            }
            s_emit[out] = '\r';     /* 先回车 */
            out++;
            s_emit[out] = '\n';     /* 再换行 */
            out++;
        } else {
            s_emit[out] = c;
            out++;
        }

        /* 到这里这个源字节才算真正被消费掉，推进读指针。*/
        s_tail = (s_tail + 1U) & (APP_LOG_RING_SIZE - 1U);
        consumed++;
    }

    /* 一个字节都没能发出（理论上只在 APP_LOG_CHUNK < 2 时才会发生），
     * 那就不要调打印函数，避免发一个空字符串白白停顿一次。*/
    if (out == 0U) {
        return 0U;
    }

    s_emit[out] = '\0';

    /* 唯一的硬件调用点。这一句会让 CPU 停顿若干时间（见 app_log.h），
     * 所以它被放在主循环里、在服务完 uart1 之后。*/
    bsp_printf("%s", s_emit);

    return out;
}
