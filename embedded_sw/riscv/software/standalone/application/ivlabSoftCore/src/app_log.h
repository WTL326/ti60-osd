/******************************************************************************
*
* @file app_log.h: 调试输出通道
*
* @brief 软核的日志接口：先把消息排队，再由主循环一小段一小段地发出去。
*
* @note 调试输出去哪了：走的是 BSP 的 semihosting 通路，也就是通过 JTAG 调试器
*       打到调试控制台上，**不是** uart0 的硬件串口引脚。
*       现场没有可用的串口适配器，uart0 的引脚接不出来，所以只能用 semihosting。
*
* @note 以下三件事容易搞错，写在最前面：
*
*       1) 这里的日志通道不是标准 C 库的 printf。
*          common/syscalls.c 里的 _write 是个空壳（直接把长度返回、什么都不做），
*          所以标准 printf 的输出会被静默丢弃、什么也看不到。
*          想打日志就用 app_log()（或 BSP 自己的格式化打印接口）。
*
*       2) semihosting 是**阻塞**的，而且停多久不由我们决定。
*          每输出一个字符，CPU 都要发一条特殊的指令（ebreak）让调试器来取，
*          在主机响应之前 CPU 完全停住。这期间 uart1 的接收中断也不会被服务。
*          这就是"日志必须排队、分段发送"的根本原因——见下面的说明。
*
*       3) 本模块不 include 任何协议相关的头文件，协议模块也不 include 本模块。
*          两条通道在代码层面就是分开的。
*
* @note 为什么要排队而不是直接打印：
*       如果收到一帧就立刻打印一整行日志，这一行里的每个字符都会让 CPU 停一次，
*       整行打完可能要好几毫秒。这几毫秒里 uart1 收不到任何数据，如果对端正在
*       连续发帧，就会丢数据。
*       排队 + 分段之后，最坏情况从"一次停 N 个字符的时间"变成"每段之间都能
*       回头服务一次 uart1"，把影响压到最小。
*
******************************************************************************/
#ifndef IVLAB_APP_LOG_H
#define IVLAB_APP_LOG_H

#include <stdint.h>

/* app_log_flush() 单次最多输出多少个字符。
 *
 * 这个值是一对矛盾：取小了，每段停顿短、对 uart1 友好，但积压的日志要很多次
 * 才能发完、整体变慢；取大了则相反。32 是折中值。
 * 如果实测发现主机响应很慢（比如每字符几毫秒），把这个值再调小。*/
#define APP_LOG_CHUNK 32U

/* 日志环的容量（字节）。必须是 2 的幂——取模用位与实现，见 app_log.c。
 *
 * 1 KB 的来历：日志的**发送**被推迟到串口线路静默之后（见 main.c 的主循环），
 * 所以这个环要能装下"一整批数据期间产生的全部消息"。抑制重复之后一轮掩膜上传
 * 只产生约 5 条（≈300 字节），512 也够，但那样没有余量——一旦装不下，消息会
 * 是"静默消失"，又会变成一次难查的排查。多花 512 字节换掉那种风险很划算。*/
#define APP_LOG_RING_SIZE 1024U

/******************************************************************************
* @brief 清空所有排队的日志，并把计数清零。
*
* @note 启动时调用一次。
******************************************************************************/
void app_log_init(void);

/******************************************************************************
* @brief 把一条格式化好的消息排进队列，稍后由主循环发出。
*
* @param format 格式串，后面跟可变参数。
*
* @note 支持的格式符：%s %c %d %u %x %X %p %%。
*       **不支持宽度和精度**（比如 %08x、%-10s），也**不支持浮点**（%f）。
*       原因见 app_log.c 开头——用标准库的格式化函数会把约 55 KB 的代码拖进来，
*       而本工程 124 KB 的 RAM 区域负担不起。
*
* @note 格式串末尾**不用写 "\n"**：本函数会自动补一个换行，每条日志各占一行。
*       真正发给串口的 "\r\n" 由 app_log_flush() 展开，不必在这里操心。
*
* @note 消息是"整条进队或整条丢弃"：如果剩余空间放不下完整一条，就整条丢掉并
*       计数，不会只塞进去半条。这样日志读起来不会出现莫名其妙的断句。
*
* @note 本函数**不碰硬件**（只操作内存里的环），所以在几乎任何地方调用都安全。
*       唯一的例外是中断服务程序——不是因为它不安全，而是因为日志本身会带来
*       停顿，在中断里攒日志没有意义。
******************************************************************************/
void app_log(const char *format, ...);

/******************************************************************************
* @brief 同一"类"消息只报首次；之后再调用不再产生任何输出。
*
* @param bitno  类别编号，0–31。习惯上直接传枚举值（如失败原因码）。
* @param format 格式串，后面跟可变参数。格式符限制与 app_log 相同。
*
* @note 用途是把"反复出现的同一类问题"压成一行。本应用需要它是因为实测发现：
*       在"只做协议框架"阶段每个掩膜帧都会失败、于是每帧打一行日志，而这些
*       日志的 semihosting 停顿会把 uart1 的接收环冲垮、导致分块大量丢失
*       （26 个包只回了 10 个应答）。详见 app_log.c 里的详细说明。
*
* @note 它不会掩盖新问题：任何一类**新的**失败都仍会被报出来。规模由周期性
*       的 stats 汇总行体现。
*
* @note bitno MUST 小于 32（越界时本函数直接返回、不输出，也不会产生副作用）。
******************************************************************************/
void app_log_once(uint32_t bitno, const char *format, ...);

/******************************************************************************
* @brief 把队列里最多 APP_LOG_CHUNK 个字符真正发出去。
*
* @return 实际发出的字符数（换行展开之后的字节数）。
*
* @note 这是本模块里**唯一**会碰调试硬件的函数。
*       调用位置很关键：必须在主循环里、且要在服务完 uart1 之后调用。
*       见 main.c 的主循环顺序。
*
* @note 它会把每个 '\n' 展开成 "\r\n" 两个字节再发出。原因是终端里
*       '\r' 负责回到行首、'\n' 负责下移一行；只发 '\n' 会让日志呈阶梯状错位。
*       本工程的既有代码（memTest 等）也都是显式写 "\r\n" 的。
*       展开集中在这一处，所以调用者无论不写换行（由 app_log 自动补）还是在
*       消息正文里自己写了 '\n'，最终都能正确换行。
*
* @note 队列为空时立即返回 0，不做任何硬件操作。
******************************************************************************/
uint32_t app_log_flush(void);

/******************************************************************************
* @brief 队列里还有多少字符没发。
******************************************************************************/
uint32_t app_log_pending(void);

/******************************************************************************
* @brief 因为队列满了而被整条丢弃的消息数。
*
* @note 这个数非零，说明日志产生速度超过了输出速度（通常是主机端太慢，
*       或者某段代码在刷屏）。它也是"调试输出是否影响了正常业务"的参考指标。
******************************************************************************/
uint32_t app_log_dropped(void);

#endif /* IVLAB_APP_LOG_H */
