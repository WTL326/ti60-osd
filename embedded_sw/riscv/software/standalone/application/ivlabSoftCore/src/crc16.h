/******************************************************************************
*
* @file crc16.h: 0xBB 协议使用的 CRC-16/CCITT 校验
*
* @brief 参数集：多项式 0x1021、初值 0x0000、输入输出都不反射、末尾不做异或。
*        只覆盖协议帧的 body 部分（不覆盖帧头、长度、CRC 自身和帧尾）。
*
* @note 这个文件刻意不依赖任何硬件（只 include <stdint.h>），原因见 frame.h：
*       保持"纯计算"，就能把协议逻辑拿到 PC 或 qemu 上跑测试，不需要 FPGA。
*
******************************************************************************/
#ifndef IVLAB_CRC16_H
#define IVLAB_CRC16_H

#include <stdint.h>

/******************************************************************************
* @brief 把一个字节"折"进正在计算的 CRC。
*
* @param crc  当前累计值。计算一个 body 时，第一次调用传入 0x0000。
* @param data 本次要折进去的 body 字节。
* @return     折入该字节后的新累计值。
*
* @note 算法与 src/control/RtlMaskUartAxiWriter.v 里的 crc16_byte() 逐位一致。
*       这一点很关键：软核端点和 RTL 端点必须对同一串字节算出同一个 CRC，
*       否则同一个上位机命令发给哪一端、结果会不一样。所以这里不是"随便选
*       一个 CRC 算法"，而是精确复刻 RTL 的写法。
*
* @note 为什么是"逐字节累加"而不是"一次算完一整块"：
*       协议帧的 body 最长可达 4999 字节，如果在软核里先缓存整块再算，就要
*       额外占 5 KB RAM。逐字节累加只需要一个 16 位变量，字节收到即算、算完
*       即丢，内存占用与帧长无关。
*
******************************************************************************/
uint16_t crc16_ccitt_update(uint16_t crc, uint8_t data);

#endif /* IVLAB_CRC16_H */
