/******************************************************************************
*
* @file bsp.h（测试替身）
*
* @brief 这是 BSP 头文件的"替身"，只在离机测试里使用，**不是**真正的 bsp.h。
*
* @note 为什么需要它：
*       app_log.c 里有 `#include "bsp.h"`，而真正的 bsp.h 会一路拖进 semihosting、
*       打印库、SoC 寄存器定义等一大串只在上板时才有意义的东西，测试台没有这些。
*       但我们确实想测试 app_log.c 里那段"把 '\n' 展开成 \r\n"的逻辑——它是纯
*       字符串处理，与硬件无关，完全值得测。
*
*       做法：在测试的 include 搜索路径里**把这个目录排在真正的 BSP 前面**，
*       于是 app_log.c 的 `#include "bsp.h"` 就找到了这份替身。app_log.c 源码
*       一行都不用改，被测的仍是正式那份代码。
*
*       搜索顺序说明：C 语言里 `#include "x.h"` 先找"包含它的那个文件所在目录"
*       （即 src/），找不到再按 -I 逐个找。src/ 下没有 bsp.h，所以 -I 的顺序
*       决定了命中哪一份——测试的 makefile 里把 stub 放在最前面。
*
* @note 替身只需要提供 app_log.c 真正用到的那一个东西：bsp_printf。
*       app_log.c 只用到它一个，所以这份替身就这么短。
*
******************************************************************************/
#ifndef IVLAB_TEST_STUB_BSP_H
#define IVLAB_TEST_STUB_BSP_H

/******************************************************************************
* @brief 测试用的打印替身：把输出收进内存缓冲，供断言检查。
*
* @param format 格式串。替身只实现 app_log.c 实际用到的一种：%s。
* @param ...    可变参数。
*
* @note 实现见 test/harness.c（它负责"测试环境"这一层）。
*
******************************************************************************/
void stub_bsp_printf(const char *format, ...);

/* 把 app_log.c 里的 bsp_printf 换成替身。
 * 用宏替换而不是提供同名函数，是因为 bsp_printf 在真正的 BSP 里可能本身就是
 * 宏或 static 函数，用宏可以确保无论哪种形式都能被替换掉。*/
#define bsp_printf stub_bsp_printf

#endif /* IVLAB_TEST_STUB_BSP_H */
