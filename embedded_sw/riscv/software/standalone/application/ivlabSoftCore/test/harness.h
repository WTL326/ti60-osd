/******************************************************************************
*
* @file harness.h: 最小裸机测试台
*
* @brief 给离机测试用的输出与断言工具。
*
* @note 测试跑在哪：在 qemu 模拟的 RISC-V 虚拟机上（qemu-system-riscv32 的
*       "virt" 机型）。两件事靠它：
*         输出 —— 往地址 0x10000000 的串口芯片写字节，qemu 会把它显示出来；
*         结果 —— 往地址 0x100000 的"关机设备"写一个值，qemu 会带着我们指定的
*                 退出码退出。于是**测试结果就是进程退出码**，Makefile 可以
*                 直接判断成败，不需要人去看输出。
*
* @note 为什么没有用 C 标准库：
*       这里没有 printf、没有 string.h，格式化、字符串处理都是本文件自己写的。
*       原因有两个：
*         1) 被测代码（../src 下的模块）是刻意做成零依赖的纯逻辑，
*            测试台如果拉着标准库，就会把标准库的依赖也算到测试头上；
*         2) 这段代码还要在真实的软核上不成立——它只在 qemu 上跑，
*            所以可以放开手脚，不必迁就嵌入式平台的种种限制。
*
******************************************************************************/
#ifndef IVLAB_TEST_HARNESS_H
#define IVLAB_TEST_HARNESS_H

/* 本头文件用到了 uint32_t，就必须自己包含 <stdint.h>。
 * 不能指望"调用方会先包含"——那只是碰巧成立，换个包含顺序就编不过。
 * 头文件自足是 C 的基本约定。*/
#include <stdint.h>

/******************************************************************************
* @brief 往测试控制台输出一个字符串。
*
* @param s 以 '\0' 结尾的字符串。
*
* @note 内部会把 '\n' 自动展开成 "\r\n"，因为串口终端通常需要回车+换行
*       两个字符才能真正换到下一行开头。
******************************************************************************/
void h_puts(const char *s);

/******************************************************************************
* @brief 格式化输出。
*
* @param format 格式串，支持 %s %c %d %u %x %%。不支持宽度、精度、浮点。
*
* @note 与 src/app_log.c 里的格式化器是同一套思路（只实现用得到的格式符），
*       但这里是独立的一份实现——测试台不应该依赖被测代码，否则被测代码
*       本身出错时，连"测试没通过"这句话都可能打不出来。
******************************************************************************/
void h_printf(const char *format, ...);

/******************************************************************************
* @brief 记录一条断言。
*
* @param ok   断言是否成立（非 0 表示成立）。
* @param name 这条断言在检查什么，会原样打印出来。
*
* @note 每条断言都会立刻打印 PASS 或 FAIL。为什么不等全部跑完再汇总输出：
*       因为裸机测试一旦中途跑飞，后面就不会再有输出了；即时打印能让人看到
*       "最后一个 PASS 是哪条"，直接定位到哪里出的问题。
*
* @note 失败的断言会累加计数，最终成为 qemu 的退出码。
******************************************************************************/
void h_check(int ok, const char *name);

/******************************************************************************
* @brief 目前累计失败的断言数。
******************************************************************************/
int h_failures(void);

/******************************************************************************
* @brief 打印总结，并让 qemu 以"失败数"为退出码退出。
*
* @note 全部通过时退出码为 0；有失败时退出码就是失败条数。
*       这样 `make` 能直接根据退出码判断成败，也能一眼看出错了几条。
******************************************************************************/
void h_done(void);

/******************************************************************************
* 输出捕获区
*
* 用途：被测代码（app_log.c）通过 bsp_printf 输出，测试台用 stub_bsp_printf
*       （见 stub/bsp.h）把它收进这里的缓冲，测试再用下面的接口取出来逐字节
*       断言。这样无需硬件、无需调试器，就能验证"到底发出去了哪些字节"。
*
* 注意捕获的是**原始字节**，包含 '\r' 和 '\n'，不做任何转换——正因为如此，
* 才能验证 app_log_flush() 有没有正确地把 '\n' 展开成 "\r\n"。
******************************************************************************/

/******************************************************************************
* @brief 清空捕获区。
******************************************************************************/
void h_capture_reset(void);

/******************************************************************************
* @brief 取捕获到的内容（以 '\0' 结尾）。
******************************************************************************/
const char *h_capture_text(void);

/******************************************************************************
* @brief 捕获到的字节数。
******************************************************************************/
uint32_t h_capture_len(void);

/******************************************************************************
* @brief 断言捕获到的内容恰好等于 expected（含长度）。
*
* @param expected 期望的完整字节序列（以 '\0' 结尾的字符串）。
* @param name     断言名。
*
* @note 失败时会把期望值与实际值都按可见形式打印出来，方便直接看出差异
*       ——尤其是 '\r' 这类看不见的字符，肉眼看输出是分辨不出来的。
******************************************************************************/
void h_check_capture(const char *expected, const char *name);

#endif /* IVLAB_TEST_HARNESS_H */
