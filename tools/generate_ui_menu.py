nodes=[]
pages=[(0x0000,-1)]
def add(items,parent=-1,path=()):
    for label,children in items:
        idx=len(nodes); nodes.append((parent,label))
        node_path=path+(label,)
        if children:
            if node_path not in PAGE_PATH_IDS:
                raise ValueError("missing stable page ID for %r" % (node_path,))
            pages.append((PAGE_PATH_IDS[node_path],idx))
        add(children,idx,node_path)
